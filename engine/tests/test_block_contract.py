"""Drift guard for the frozen block-wire contract.

The contract artifacts under ``contract/`` (``block-types.md`` and
``fixtures/blocks.jsonl``) are GENERATED by ``scripts/gen_block_contract.py``
from the live code. These tests regenerate them in-memory and assert the
committed files match byte-for-byte — so the doc + fixtures can never silently
rot away from ``blocks.py`` / ``events.py`` / ``errors.py`` again (the exact
class of bug — a hand-written table drifting from the code — that motivated
this contract). They also assert the fixtures are real, parseable SSE frames,
one per block type plus the two synthesized terminals.

Real, no mocks: the generator runs the live fold; the assertions read the
committed artifacts off disk.
"""

from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from scripts.gen_block_contract import (  # noqa: E402
    render_markdown,
    render_fixtures,
    MD_PATH,
    FIXTURES_PATH,
)
from src.engine_core.blocks import BLOCK_TYPES  # noqa: E402


def read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def test_block_types_count():
    """The vocabulary is exactly 27 types (the contract's spine)."""
    assert len(BLOCK_TYPES) == 27
    assert len(set(BLOCK_TYPES)) == 27


def test_contract_md_in_sync():
    """contract/block-types.md must equal a fresh render — the drift guard.

    If this fails, the live code changed: rerun
    ``python scripts/gen_block_contract.py`` and commit the regenerated doc.
    """
    assert os.path.exists(MD_PATH), (
        f"{MD_PATH} missing — run `python scripts/gen_block_contract.py`"
    )
    assert read(MD_PATH) == render_markdown(), (
        "contract/block-types.md drifted from the code — "
        "rerun `python scripts/gen_block_contract.py` and commit."
    )


def test_fixtures_in_sync():
    """contract/fixtures/blocks.jsonl must equal a fresh render of the frames."""
    assert os.path.exists(FIXTURES_PATH), (
        f"{FIXTURES_PATH} missing — run `python scripts/gen_block_contract.py`"
    )
    assert read(FIXTURES_PATH) == "".join(render_fixtures()), (
        "contract/fixtures/blocks.jsonl drifted from the code — "
        "rerun `python scripts/gen_block_contract.py` and commit."
    )


def parse_frame(frame: str) -> dict:
    """Parse one SSE frame string ("seq: N\\nevent: block\\ndata: {json}\\n\\n")
    into its decoded data object, asserting the framing along the way."""
    lines = frame.split("\n")
    assert lines[0].startswith("seq: "), f"missing seq line: {frame!r}"
    int(lines[0][len("seq: ") :])
    assert lines[1] == "event: block", f"missing event line: {frame!r}"
    assert lines[2].startswith("data: "), f"missing data line: {frame!r}"
    assert lines[3] == "" and lines[4] == "", f"frame must end with blank line: {frame!r}"
    return json.loads(lines[2][len("data: ") :])


def test_fixtures_parse():
    """Every fixture frame parses to valid JSON with the five envelope keys, and
    there is exactly one fixture per BLOCK_TYPES entry (done + error included)."""
    frames = render_fixtures()
    assert len(frames) == len(BLOCK_TYPES)

    seen_types: list[str] = []
    for frame in frames:
        data = parse_frame(frame)
        assert set(data.keys()) == {"id", "type", "thread_id", "ts", "payload"}, (
            f"frame keys != envelope keys: {data.keys()}"
        )
        assert isinstance(data["payload"], dict)
        assert data["id"], "every fixture must carry a derived id"
        seen_types.append(data["type"])

    assert sorted(seen_types) == sorted(BLOCK_TYPES)
    assert len(set(seen_types)) == len(BLOCK_TYPES)
    assert "done" in seen_types
    assert "error" in seen_types
